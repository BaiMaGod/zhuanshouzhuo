// Offline topology selection. The game imports only the saved result.
import {writeFileSync} from 'node:fs';
import {campaignLayout} from '../src/campaign-layout.js';
const mod=(n,d)=>((n%d)+d)%d;
const output={};
for(let number=11;number<=100;number++){
 if(number===45)continue;
 const nodes=campaignLayout(number+9),N=nodes.length;
 const adj=nodes.map(p=>nodes.map((q,i)=>Math.abs(Math.hypot(q.x-p.x,q.y-p.y)-92.0001)<.01?i:-1).filter(i=>i>=0));
 const colors=nodes.map(p=>mod(Math.round(p.x/92.0001-1.5*p.y/(92.0001*Math.sqrt(3)/2)),3));
 let best=null;
 for(let phase=0;phase<3;phase++)for(let variant=0;variant<12;variant++){
  const centers=nodes.map((_,i)=>i).filter(i=>colors[i]===phase);
  // A cut along the oval boundary can leave a cell without a center neighbor.
  for(let i=0;i<N;i++)if(!centers.includes(i)&&!adj[i].some(j=>centers.includes(j)))centers.push(i);
  const receivers=nodes.map((_,i)=>i).filter(i=>!centers.includes(i));
  const left=receivers.filter(i=>colors[i]===mod(phase+1,3)),right=new Set(receivers.filter(i=>colors[i]===mod(phase+2,3)));
  const rank=i=>mod(Math.imul(i+1,1103515245)+Math.imul(number+variant*97,12345),2147483647);
  const matched=new Map();
  function augment(a,seen){
   for(const b of adj[a].filter(i=>right.has(i)).sort((a,b)=>rank(a)-rank(b))){
    if(seen.has(b))continue;seen.add(b);
    if(!matched.has(b)||augment(matched.get(b),seen)){matched.set(b,a);return true}
   }
   return false;
  }
  for(const a of left.sort((a,b)=>rank(a)-rank(b)))augment(a,new Set());
  const pairs=[...matched].map(([b,a])=>[a,b]),protectedIds=new Set(pairs.flat());
  const mounts=centers.flatMap(c=>adj[c].map(r=>[c,r]));
  const seen=new Set([centers[0]]);
  for(let t=0;t<N;t++)for(const [a,b]of[...mounts,...pairs])if(seen.has(a)||seen.has(b)){seen.add(a);seen.add(b)}
  if(seen.size!==N)continue;
  const holds=centers.map(c=>adj[c].filter(r=>protectedIds.has(r)).length);
  const hard=holds.filter(n=>n>=2).length;
  const score=hard*100+protectedIds.size*5-Math.max(...holds)*2;
  if(!best||score>best.score)best={centers:centers.sort((a,b)=>a-b),pairs,score,hard};
 }
 if(!best||best.hard<2)throw Error('Missing verified topology '+number);
 output[number]={centers:best.centers,pairs:best.pairs};
}
writeFileSync('src/formal-templates.js','// Generated by scripts/generate-formal-templates.mjs; zero-based lattice cells.\nexport default '+JSON.stringify(output)+';\n');
console.log('Saved '+Object.keys(output).length+' mixed-clasp campaign templates.');
