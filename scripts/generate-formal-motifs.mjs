// Generate five topology families from the last fully validated campaign templates.
// This runs offline; game clients read only the resulting selection masks.
// Usage: node scripts/generate-formal-motifs.mjs
import {writeFileSync} from 'node:fs';
import base from '../src/formal-templates.js';
import {campaignLayout} from '../src/campaign-layout.js';

const SPACING=92.0001;
const hash=(a,b,n)=>((Math.imul(a+33,73856093)^Math.imul(b+79,19349663)^Math.imul(n+43,83492791))>>>0);
const FAMILIES=['branch','focal','weave','sparse','alternating'];
const PAIR_RATIO=[.45,.60,.85,.38,.68];
const MOUNT_RATIO=[.63,.72,.78,.57,.70];
const HOLD_RATIO=[.16,.27,.46,.16,.35];

export function selectMotif(template,number){
 const nodes=campaignLayout(number+9),N=nodes.length,C=template.centers,P=template.pairs;
 const M=C.flatMap(c=>nodes.map((p,r)=>
  Math.abs(Math.hypot(nodes[c].x-p.x,nodes[c].y-p.y)-SPACING)<.01?[c,r]:null).filter(Boolean));
 const mAlive=M.map(()=>true),pAlive=P.map(()=>true),family=number%FAMILIES.length;
 const minHolds=Math.max(2,Math.floor(C.length*HOLD_RATIO[family]));
 function inspect(){
  const parent=Array.from({length:N},(_,i)=>i);
  const root=i=>{while(i!==parent[i]){parent[i]=parent[parent[i]];i=parent[i]}return i};
  const connect=(a,b)=>{a=root(a);b=root(b);parent[a]=b};
  const ownerDegree=new Int16Array(N),receiverDegree=new Int16Array(N),fixed=new Uint8Array(N);
  for(let i=0;i<P.length;i++)if(pAlive[i]){
   const [a,b]=P[i];connect(a,b);fixed[a]=fixed[b]=1;
  }
  for(let i=0;i<M.length;i++)if(mAlive[i]){
   const [c,r]=M[i];ownerDegree[c]++;receiverDegree[r]++;connect(c,r);
  }
  let holds=0;
  for(const c of C){
   let count=0;
   for(let i=0;i<M.length;i++)if(mAlive[i]&&M[i][0]===c&&fixed[M[i][1]])count++;
   if(count>=2)holds++;
  }
  return {ownerDegree,receiverDegree,holds,
   connected:parent.every((_,i)=>root(i)===root(0)),
   shared:receiverDegree.some(n=>n>=2)};
 }
 const pairTarget=Math.ceil(P.length*PAIR_RATIO[family]);
 const pairOrder=P.map((_,i)=>i).sort((a,b)=>hash(...P[a],number)-hash(...P[b],number));
 for(const i of pairOrder){
  if(pAlive.filter(Boolean).length<=pairTarget)break;
  pAlive[i]=false;
  const result=inspect();
  if(!result.connected||result.holds<minHolds)pAlive[i]=true;
 }
 const mountTarget=Math.ceil(M.length*MOUNT_RATIO[family]);
 for(let attempt=0;attempt<M.length&&mAlive.filter(Boolean).length>mountTarget;attempt++){
  const state=inspect();
  const weight=i=>{
   const [c,r]=M[i],j=C.indexOf(c);
   const cap=family===0?3:family===1?(j%5===number%5?6:2)
    :family===2?4:family===3?2:2+(j*7+number)%4;
   return (state.ownerDegree[c]>cap?10000:0)+state.ownerDegree[c]*1000+
    (state.receiverDegree[r]>1?500:0)+hash(c,r,number)/2**32;
  };
  const candidates=M.map((_,i)=>i).filter(i=>mAlive[i]).sort((a,b)=>weight(b)-weight(a));
  let removed=false;
  for(const i of candidates){
   const [c,r]=M[i];
   if(state.ownerDegree[c]<=1||state.receiverDegree[r]<=1)continue;
   mAlive[i]=false;
   const check=inspect();
   if(check.connected&&check.holds>=minHolds&&check.shared){removed=true;break;}
   mAlive[i]=true;
  }
  if(!removed)break;
 }
 const result=inspect();
 if(!result.connected||!result.shared||result.holds<2||
    C.some(c=>!result.ownerDegree[c])||
    nodes.some((_,i)=>!C.includes(i)&&!result.receiverDegree[i]))
  throw Error('Invalid topology on formal level '+number);
 return {family:FAMILIES[family],
  mounts:mAlive.map(on=>on?'1':'0').join(''),
  pairs:pAlive.map(on=>on?'1':'0').join('')};
}
const output={};
for(let n=11;n<=100;n++){
 if(n===45)continue;
 output[n]=selectMotif(base[n],n);
}
const filename='src/formal-motifs.js';
writeFileSync(filename,
 '// Generated by scripts/generate-formal-motifs.mjs. Masks index the unmodified seed topology.\n'+
 'export default '+JSON.stringify(output)+';\n');
console.log('Saved '+Object.keys(output).length+' diverse formal topology masks.');